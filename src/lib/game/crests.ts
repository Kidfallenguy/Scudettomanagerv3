export function crestUrl(clubId: string): string {
  if (RESERVE_TEAM_PARENTS[clubId]) return crestUrl(RESERVE_TEAM_PARENTS[clubId]!);
  if (USER_SUPPLIED_CRESTS[clubId]) return USER_SUPPLIED_CRESTS[clubId]!;
  if (LALIGA_ESPAÑOLA_CRESTS.has(clubId)) return `/crests/LALIGAESPAÑOLA/${clubId}.png`;
  if (clubId === "sd_rsb") return "/crests/rso.png";
  if (clubId === "sd_cef") return "/crests/cel.png";
  if (clubId === "gir") return "/crests/LALIGAESPAÑOLA/gir.png";
  if (clubId === "pf_ath") return crestUrl("ath");
  if (clubId === "pf_atm") return crestUrl("atl");
  if (clubId === "pf_fab") return crestUrl("dep");
  if (clubId === "pf_rmc") return crestUrl("rma");
  if (clubId === "pf_vlb") return crestUrl("vil");
  if (clubId in LEAGUE_ONE_CRESTS) return LEAGUE_ONE_CRESTS[clubId];
  if (SVG_IDS.has(clubId)) return `/crests/${clubId}.svg`;
  if (PNG_IDS.has(clubId)) return preferredCrestPath(clubId);
  return "";
}
