import { mkdir, readdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const pendingFacesRoot = path.join(root, "FACES", "poner");
const sourceRoots = [
  path.join(root, "FACES", "WONDERKIDSFACES"),
  pendingFacesRoot,
];
const outputRoot = path.join(root, "public", "player-faces", "wonderkids");
const configPath = path.join(
  root,
  "src",
  "lib",
  "game",
  "wonderkid-face-config.ts",
);
const faceSize = 64;
const atlasColumns = 8;
const facesPerAtlas = atlasColumns * atlasColumns;
const firstAtlasToBuild = Number(process.argv[2] ?? 0);
const imageExtensions = new Set([".png", ".jpg", ".jpeg", ".webp"]);

async function collectImages(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((left, right) =>
    left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
  );

  const files = [];
  for (const entry of entries) {
    const filePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectImages(filePath)));
    } else if (
      entry.isFile() &&
      imageExtensions.has(path.extname(entry.name).toLowerCase())
    ) {
      files.push(filePath);
    }
  }
  return files;
}

const files = [];
for (const sourceRoot of sourceRoots) {
  const sourceFiles = await collectImages(sourceRoot);
  for (const filePath of sourceFiles) {
    const fileName = path.basename(filePath);
    const isPendingFace = sourceRoot === pendingFacesRoot;
    // In poner, 3-letter suffixes are flags and 001-numeric IDs are club crests.
    if (
      fileName.toLowerCase() === "imagen_predeterminada_original.png" ||
      (isPendingFace &&
        (/^\d{3}-[a-z]{3}\.png$/i.test(fileName) ||
          /^001-\d+\.png$/i.test(fileName)))
    ) {
      continue;
    }
    files.push(filePath);
  }
}
if (files.length === 0) {
  throw new Error(`No player faces found in ${sourceRoots.join(", ")}`);
}

const atlasCount = Math.ceil(files.length / facesPerAtlas);
if (
  !Number.isInteger(firstAtlasToBuild) ||
  firstAtlasToBuild < 0 ||
  firstAtlasToBuild >= atlasCount
) {
  throw new Error(`Invalid first atlas index: ${process.argv[2]}`);
}

await mkdir(outputRoot, { recursive: true });

if (firstAtlasToBuild > 0) {
  const existing = new Set(
    (await readdir(outputRoot)).filter((name) =>
      /^atlas-\d{4}\.webp$/.test(name),
    ),
  );
  for (let atlasIndex = 0; atlasIndex < firstAtlasToBuild; atlasIndex++) {
    const name = `atlas-${String(atlasIndex).padStart(4, "0")}.webp`;
    if (!existing.has(name)) {
      throw new Error(`Cannot resume atlas build; missing ${name}`);
    }
  }
}

for (
  let atlasIndex = firstAtlasToBuild;
  atlasIndex < atlasCount;
  atlasIndex++
) {
  const start = atlasIndex * facesPerAtlas;
  const atlasFiles = files.slice(start, start + facesPerAtlas);
  const composites = [];

  for (let offset = 0; offset < atlasFiles.length; offset += 32) {
    const tiles = await Promise.all(
      atlasFiles.slice(offset, offset + 32).map(async (filePath, index) => {
        try {
          const input = await sharp(filePath)
            .rotate()
            .resize(faceSize, faceSize, { fit: "cover" })
            .webp({ quality: 70, effort: 4 })
            .toBuffer();
          const faceIndex = offset + index;
          return {
            input,
            left: (faceIndex % atlasColumns) * faceSize,
            top: Math.floor(faceIndex / atlasColumns) * faceSize,
          };
        } catch (error) {
          throw new Error(`Unable to process player face: ${filePath}`, {
            cause: error,
          });
        }
      }),
    );
    composites.push(...tiles);
  }

  const outputPath = path.join(
    outputRoot,
    `atlas-${String(atlasIndex).padStart(4, "0")}.webp`,
  );
  await sharp({
    create: {
      width: faceSize * atlasColumns,
      height: faceSize * atlasColumns,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite(composites)
    .webp({ quality: 70, effort: 4 })
    .toFile(outputPath);

  if (
    (atlasIndex + 1) % 128 === 0 ||
    start + atlasFiles.length === files.length
  ) {
    console.log(
      `Generated ${atlasIndex + 1} atlases from ${start + atlasFiles.length}/${files.length} faces.`,
    );
  }
}

for (const entry of await readdir(outputRoot, { withFileTypes: true })) {
  if (!entry.isFile()) continue;
  const match = /^atlas-(\d{3,4})\.webp$/.exec(entry.name);
  if (match && (match[1].length === 3 || Number(match[1]) >= atlasCount)) {
    await unlink(path.join(outputRoot, entry.name));
  }
}

await writeFile(
  configPath,
  `// Generated by npm run build:wonderkid-atlases.\nexport const WONDERKID_FACE_COUNT = ${files.length};\nexport const WONDERKID_ATLAS_COLUMNS = ${atlasColumns};\nexport const WONDERKID_FACE_SIZE = ${faceSize};\n`,
);

console.log(`Generated ${files.length} player faces in WebP atlases.`);
